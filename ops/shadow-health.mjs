import { readFileSync, appendFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { setTimeout as delay } from 'node:timers/promises';

const directory = dirname(fileURLToPath(import.meta.url));
const marker = '<!-- nre-shadow-health: generated by ops/shadow-health.mjs -->';
const title = 'NRE Shadow: active infrastructure incidents';
const ownerRepo = 'Willn0tBill/NRE';
const githubApi = 'https://api.github.com';
const failureConclusions = new Set(['failure', 'timed_out', 'action_required', 'startup_failure']);

async function api(path, options = {}) {
  const headers = {
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
    'User-Agent': 'NRE-Shadow-Health/1.0',
  };
  if (options.authenticated) {
    if (!process.env.GITHUB_TOKEN) throw new Error('GITHUB_TOKEN is missing');
    headers.Authorization = 'Bearer ' + process.env.GITHUB_TOKEN;
  }
  if (options.body !== undefined) headers['Content-Type'] = 'application/json';
  const response = await fetch(githubApi + path, {
    method: options.method || 'GET',
    headers,
    body: options.body === undefined ? undefined : JSON.stringify(options.body),
    signal: AbortSignal.timeout(15000),
  });
  if (!response.ok) throw new Error('GitHub API HTTP ' + response.status + ' for ' + path);
  return response.json();
}

export function latestMainWorkflowFailures(runs, now = new Date()) {
  const cutoff = now.getTime() - 21 * 24 * 60 * 60 * 1000;
  const seen = new Set();
  const incidents = [];
  for (const run of [...runs].sort((a, b) => String(b.created_at).localeCompare(String(a.created_at)))) {
    if (run.head_branch !== 'main' || run.status !== 'completed' || run.event === 'pull_request') continue;
    const key = String(run.workflow_id || run.name);
    if (seen.has(key)) continue;
    seen.add(key);
    if (new Date(run.created_at).getTime() < cutoff) continue;
    if (failureConclusions.has(run.conclusion)) {
      incidents.push({
        name: run.name || 'Unnamed workflow',
        detail: 'Latest completed main-branch run: ' + run.conclusion,
        url: run.html_url,
      });
    }
  }
  return incidents;
}

async function checkSite(site) {
  let lastError = 'Unknown error';
  for (let attempt = 0; attempt < 2; attempt += 1) {
    try {
      const result = await fetch(site.url, {
        method: 'GET',
        headers: { 'User-Agent': 'NRE-Shadow-Health/1.0', 'Cache-Control': 'no-cache' },
        redirect: 'follow',
        signal: AbortSignal.timeout(12000),
      });
      if (result.ok) return null;
      lastError = 'HTTP ' + result.status;
    } catch (error) {
      lastError = error instanceof Error ? error.message : String(error);
    }
    if (attempt === 0) await delay(800);
  }
  return { name: site.name, detail: 'Endpoint failed two checks: ' + lastError, url: site.url };
}

export function renderIssueBody(incidents) {
  const rows = [...incidents].sort((a, b) => (a.name + a.url).localeCompare(b.name + b.url));
  return marker + '\n# Active incidents\n\n' +
    'This issue is managed by the hourly NRE Shadow GitHub Action. A failed check does not automatically prove a complete outage. Check linked logs and retry manually before making production changes.\n\n' +
    rows.map((item) => '- **' + item.name + '** — ' + item.detail + '\n  ' + item.url).join('\n') +
    '\n\nThe issue closes automatically when subsequent checks find no active incidents. No code or deployment is changed by this watcher.\n';
}

async function syncIssue(incidents) {
  const allIssues = await api('/repos/' + ownerRepo + '/issues?state=all&per_page=100', { authenticated: true });
  const existing = allIssues.find((issue) => !issue.pull_request && issue.title === title && (issue.body || '').includes(marker));
  if (!incidents.length) {
    if (existing && existing.state === 'open') {
      await api('/repos/' + ownerRepo + '/issues/' + existing.number, {
        method: 'PATCH', authenticated: true, body: { state: 'closed' },
      });
      return 'Closed recovered infrastructure incident issue #' + existing.number;
    }
    return 'No active incident issue needed';
  }
  const body = renderIssueBody(incidents);
  if (!existing) {
    const issue = await api('/repos/' + ownerRepo + '/issues', {
      method: 'POST', authenticated: true, body: { title, body },
    });
    return 'Opened infrastructure incident issue #' + issue.number;
  }
  if (existing.state !== 'open' || existing.body !== body) {
    await api('/repos/' + ownerRepo + '/issues/' + existing.number, {
      method: 'PATCH', authenticated: true, body: { state: 'open', body },
    });
    return 'Updated infrastructure incident issue #' + existing.number;
  }
  return 'Existing infrastructure incident issue unchanged';
}

export async function main() {
  const config = JSON.parse(readFileSync(join(directory, 'watch.json'), 'utf8'));
  const incidents = [];
  const warnings = [];
  for (const repo of config.repositories) {
    try {
      const result = await api('/repos/' + repo + '/actions/runs?per_page=40');
      const failures = latestMainWorkflowFailures(result.workflow_runs || []);
      for (const item of failures) {
        incidents.push({
          name: repo + ' / ' + item.name,
          detail: item.detail,
          url: item.url,
        });
      }
    } catch (error) {
      warnings.push(repo + ': could not inspect workflow history (' + String(error.message || error) + ')');
    }
  }
  for (const site of config.sites) {
    const failed = await checkSite(site);
    if (failed) incidents.push(failed);
  }
  const summary = [
    '## NRE Shadow — asset health',
    '',
    'Repositories checked: ' + config.repositories.length,
    'Websites checked: ' + config.sites.length,
    'Active incidents: ' + incidents.length,
    'Unverified repositories: ' + warnings.length,
    '',
    ...incidents.map((item) => '- INCIDENT: ' + item.name + ' — ' + item.detail + ' (' + item.url + ')'),
    ...warnings.map((warning) => '- UNKNOWN: ' + warning),
  ].join('\n') + '\n';
  console.log(summary);
  if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, summary);
  const result = await syncIssue(incidents);
  console.log(result);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
